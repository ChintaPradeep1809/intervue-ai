"""Seed question bank. Loaded into the `questions` table by the seed script; admins can edit it.

Each question lists expected concepts (with detection keywords) and curated follow-ups. Follow-up
triggers: "mentioned:<concept>" (candidate covered it), "missing:<concept>", or "any".
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class FollowUpSpec(BaseModel):
    type: str  # clarification | challenge | edge_case | optimization | architecture | behavioral
    trigger: str
    text: str


class ConceptSpec(BaseModel):
    name: str
    keywords: list[str]


class BankQuestion(BaseModel):
    id: str
    topic: str
    difficulty: int = Field(ge=1, le=3)
    text: str
    concepts: list[ConceptSpec]
    followups: list[FollowUpSpec] = []
    roles: list[str] = []  # empty = any role
    kind: str = "technical"  # technical | behavioral | introduction | system_design


def Q(
    qid: str,
    topic: str,
    difficulty: int,
    text: str,
    concepts: list[tuple[str, str]],
    followups: list[tuple[str, str, str]] | None = None,
    roles: list[str] | None = None,
    kind: str = "technical",
) -> BankQuestion:
    return BankQuestion(
        id=qid,
        topic=topic,
        difficulty=difficulty,
        text=text,
        concepts=[ConceptSpec(name=n, keywords=[k.strip() for k in kws.split("|") if k.strip()]) for n, kws in concepts],
        followups=[FollowUpSpec(type=t, trigger=tr, text=tx) for t, tr, tx in (followups or [])],
        roles=roles or [],
        kind=kind,
    )


